#!/usr/bin/env bash
# One-shot installer for AWS Lightsail (Ubuntu 22.04 LTS or 24.04 LTS).
#
# Usage:
#   curl -fsSL https://raw.githubusercontent.com/YOU/stack-hub/main/deploy/install.sh \
#        | sudo DOMAIN=studio.example.com EMAIL=you@example.com REPO=https://github.com/YOU/stack-hub bash
#
# Or, if you've already cloned the repo:
#   cd /tmp && git clone YOUR_REPO stack-hub-src
#   sudo DOMAIN=studio.example.com EMAIL=you@example.com bash stack-hub-src/deploy/install.sh
#
# The script is idempotent — safe to re-run. It will not overwrite an
# existing /opt/stack-hub/.env so your secrets survive re-installs.

set -euo pipefail

DOMAIN="${DOMAIN:?Set DOMAIN=studio.example.com before running}"
EMAIL="${EMAIL:?Set EMAIL=you@example.com (used by Let's Encrypt)}"
REPO="${REPO:-}"
INSTALL_DIR="/opt/stack-hub"
SERVICE_USER="stackhub"
SERVICE_GROUP="stackhub"

require_root() {
    if [[ $EUID -ne 0 ]]; then
        echo "Run with sudo." >&2
        exit 1
    fi
}

log() { printf '\n\033[1;36m==>\033[0m %s\n' "$*"; }

require_root

log "Updating apt"
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y --no-install-recommends \
    git curl ca-certificates build-essential pkg-config \
    python3 python3-venv python3-dev \
    nginx ufw certbot python3-certbot-nginx

# Node 20 (for the Vite build)
if ! command -v node >/dev/null 2>&1 || [[ "$(node -v)" != v20* && "$(node -v)" != v22* ]]; then
    log "Installing Node.js 20.x"
    curl -fsSL https://deb.nodesource.com/setup_20.x | bash -
    apt-get install -y nodejs
fi

# Service user
if ! id -u "$SERVICE_USER" >/dev/null 2>&1; then
    log "Creating $SERVICE_USER user"
    useradd --system --home "$INSTALL_DIR" --shell /usr/sbin/nologin "$SERVICE_USER"
fi

# Source: clone or use the directory containing this script
if [[ -n "$REPO" ]]; then
    log "Cloning repo $REPO into $INSTALL_DIR"
    if [[ -d "$INSTALL_DIR/.git" ]]; then
        git -C "$INSTALL_DIR" fetch --all
        git -C "$INSTALL_DIR" reset --hard origin/main
    else
        rm -rf "$INSTALL_DIR"
        git clone "$REPO" "$INSTALL_DIR"
    fi
else
    SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
    log "Copying source from $SRC_DIR to $INSTALL_DIR"
    mkdir -p "$INSTALL_DIR"
    rsync -a --delete \
        --exclude '.git' \
        --exclude '.venv' \
        --exclude 'webapp/node_modules' \
        --exclude 'webapp/dist' \
        --exclude '__pycache__' \
        --exclude '.pytest_cache' \
        --exclude '.mypy_cache' \
        --exclude '*.pyc' \
        "$SRC_DIR/" "$INSTALL_DIR/"
fi

# Python venv + deps
log "Setting up Python venv at $INSTALL_DIR/.venv"
python3 -m venv "$INSTALL_DIR/.venv"
"$INSTALL_DIR/.venv/bin/pip" install --upgrade pip wheel
"$INSTALL_DIR/.venv/bin/pip" install -r "$INSTALL_DIR/requirements.txt"

# Build the React app
log "Building React app"
cd "$INSTALL_DIR/webapp"
npm ci
npm run build
cd "$INSTALL_DIR"

# .env: generate sane defaults if missing
if [[ ! -f "$INSTALL_DIR/.env" ]]; then
    log "Generating $INSTALL_DIR/.env (edit it before going public)"
    AUTH_SECRET=$(openssl rand -hex 32)
    ADMIN_PASS=$(openssl rand -base64 12 | tr -d '/+=' | head -c 16)
    cat > "$INSTALL_DIR/.env" <<EOF
# Generated by deploy/install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# CHANGE the API keys + passwords below to your real values, then:
#   sudo systemctl restart stack-hub

LLM_PROVIDER=gemini
GEMINI_API_KEY=
GEMINI_MODEL=gemini-2.5-flash-lite

OPENAI_API_KEY=
OPENAI_MODEL=gpt-4.1

ANTHROPIC_API_KEY=
ANTHROPIC_MODEL=claude-opus-4-7

NOVITA_API_KEY=
NOVITA_MODEL=meta-llama/llama-3.3-70b-instruct
NOVITA_BASE_URL=https://api.novita.ai/v3/openai

LLM_MAX_TOKENS_DRAFT=8000
LLM_MAX_TOKENS_DETECTOR=8000
LLM_MAX_TOKENS_VOICE=4000
LLM_TEMPERATURE=0.7

# Auth — random admin password generated; copy it to a password manager NOW.
ADMIN_USERNAME=admin
ADMIN_PASSWORD=${ADMIN_PASS}
USER_USERNAME=user
USER_PASSWORD=${ADMIN_PASS}
AUTH_SECRET=${AUTH_SECRET}
AUTH_SESSION_DAYS=30

# Real-time meeting bot (optional)
RECALL_API_KEY=
EOF
    echo
    echo "================================================================"
    echo "  Initial admin credentials (saved to $INSTALL_DIR/.env)"
    echo "    username: admin"
    echo "    password: $ADMIN_PASS"
    echo "  Copy these now — they will not be shown again."
    echo "================================================================"
    echo
fi

# Permissions
chown -R "$SERVICE_USER:$SERVICE_GROUP" "$INSTALL_DIR"
chmod 600 "$INSTALL_DIR/.env"

# systemd
log "Installing systemd unit"
cp "$INSTALL_DIR/deploy/systemd/stack-hub.service" /etc/systemd/system/stack-hub.service
systemctl daemon-reload
systemctl enable stack-hub.service
systemctl restart stack-hub.service

# nginx
log "Configuring nginx for $DOMAIN"
sed "s|YOUR_DOMAIN|$DOMAIN|g" "$INSTALL_DIR/deploy/nginx/stack-hub.conf" \
    > /etc/nginx/sites-available/stack-hub.conf
ln -sf /etc/nginx/sites-available/stack-hub.conf /etc/nginx/sites-enabled/stack-hub.conf
rm -f /etc/nginx/sites-enabled/default
nginx -t
systemctl reload nginx

# Firewall (ufw)
log "Opening firewall ports (ufw)"
ufw allow OpenSSH || true
ufw allow 'Nginx Full' || true
ufw --force enable || true

# HTTPS via certbot
log "Provisioning HTTPS via Let's Encrypt"
certbot --nginx --non-interactive --agree-tos --redirect \
    --email "$EMAIL" -d "$DOMAIN"

log "All done."
echo
echo "Open: https://$DOMAIN"
echo "Logs: sudo journalctl -u stack-hub -f"
echo "Edit env + restart: sudo nano $INSTALL_DIR/.env && sudo systemctl restart stack-hub"
